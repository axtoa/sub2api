import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import ExternalQualityTools from '../ExternalQualityTools.vue'
import { qualityAPI } from '../api'
import { externalTools } from './fixtures'
import type { ExternalToolKind } from '../api'
import { resourceGroup } from '../externalResources'

vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key, te: () => true }) }))
vi.mock('@/api/client', () => ({ apiClient: { get: vi.fn(), put: vi.fn() } }))
const wrappers: ReturnType<typeof mount>[] = []
function render() { const wrapper = mount(ExternalQualityTools); wrappers.push(wrapper); return wrapper }
async function selectKind(wrapper: ReturnType<typeof mount>, kind: ExternalToolKind) {
  const group = wrapper.findAll('.quality-resource-groups button').find(button => button.text().startsWith(`quality.external.groups.${resourceGroup(kind)}`))!
  await group.trigger('click')
  await categoryButton(wrapper, kind).trigger('click')
}
function categoryButton(wrapper: ReturnType<typeof mount>, kind: ExternalToolKind) {
  return wrapper.findAll('.quality-resource-kinds button').find(button => button.text().startsWith(`quality.external.${kind}`))!
}
beforeEach(() => {
  vi.spyOn(qualityAPI, 'externalTools').mockResolvedValue(structuredClone(externalTools))
  vi.spyOn(qualityAPI, 'saveExternalTools').mockImplementation(async list => ({ ...list, version: list.version + 1 }))
})
afterEach(() => { wrappers.splice(0).forEach(w => w.unmount()); vi.restoreAllMocks() })
describe('External quality tools', () => {
  it('loads persisted links in isolated tabs and includes both model families', async () => {
    const wrapper = render(); await flushPromises(); await selectKind(wrapper, 'channel')
    expect(wrapper.findAll('article')).toHaveLength(4)
    for (const link of wrapper.findAll('a')) {
      expect(new URL(link.attributes('href')).protocol).toBe('https:')
      expect(link.attributes('target')).toBe('_blank')
      expect(link.attributes('rel')).toBe('noopener noreferrer')
      expect(link.attributes('referrerpolicy')).toBe('no-referrer')
    }
    await wrapper.get('.quality-resource-filters select').setValue('gpt')
    expect(wrapper.findAll('article')).toHaveLength(4)
    await wrapper.get('.quality-resource-filters select').setValue('claude')
    expect(wrapper.findAll('article')).toHaveLength(4)
    await categoryButton(wrapper, 'ranking').trigger('click')
    expect(wrapper.findAll('article')).toHaveLength(3)
    expect(wrapper.text()).toContain('Folkbench')
    expect(wrapper.findAll('article').some(card => card.text().includes('CCTest'))).toBe(false)
    expect(wrapper.findAll('article a')[0]!.text()).toContain('quality.external.openByKind.ranking')
    await categoryButton(wrapper, 'benchmark').trigger('click')
    expect(wrapper.findAll('article')).toHaveLength(2)
    expect(wrapper.text()).toContain('Artificial Analysis')
    expect(wrapper.text()).toContain('LiveBench')
    expect(qualityAPI.saveExternalTools).not.toHaveBeenCalled()
  })
  it('creates, edits, filters and deletes sites using the current persisted version', async () => {
    const wrapper = render(); await flushPromises(); await selectKind(wrapper, 'channel')
    await wrapper.get('.quality-external-toolbar .primary').trigger('click')
    const form = wrapper.get('form')
    await form.get('input:not([type])').setValue('My ranking')
    await form.get('input[type="url"]').setValue('https://example.com/ranking')
    await form.get('textarea').setValue('My own reference site')
    await form.get('select').setValue('ranking')
    await form.findAll('input[type="checkbox"]')[0]!.setValue(false)
    await form.findAll('input[type="checkbox"]')[1]!.setValue(true)
    await form.trigger('submit'); await flushPromises()
    expect(wrapper.findAll('article')).toHaveLength(4)
    const created = vi.mocked(qualityAPI.saveExternalTools).mock.calls[0]![0]
    expect(created.version).toBe(1)
    expect(created.items.at(-1)).toMatchObject({ name: 'My ranking', kind: 'ranking', families: ['claude'] })
    await wrapper.get('.quality-resource-filters select').setValue('gpt')
    expect(wrapper.findAll('article')).toHaveLength(3)
    await wrapper.get('.quality-resource-filters select').setValue('claude')
    await wrapper.findAll('article')[3]!.findAll('button')[0]!.trigger('click')
    await wrapper.get('form input:not([type])').setValue('Edited ranking')
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(qualityAPI.saveExternalTools).toHaveBeenLastCalledWith(expect.objectContaining({ version: 2 }))
    expect(wrapper.findAll('article')[3]!.text()).toContain('Edited ranking')
    await wrapper.findAll('article')[3]!.findAll('button')[1]!.trigger('click'); await flushPromises()
    expect(wrapper.findAll('article')).toHaveLength(3)
    expect(qualityAPI.saveExternalTools).toHaveBeenLastCalledWith(expect.objectContaining({ version: 3 }))
    expect(externalTools.items[0]!.name).toBe('CCTest')
  })
  it('defaults new websites to the selected category and moves edited websites into their new category', async () => {
    const wrapper = render(); await flushPromises(); await selectKind(wrapper, 'channel')
    await categoryButton(wrapper, 'ranking').trigger('click')
    await wrapper.get('.quality-external-toolbar .primary').trigger('click')
    expect((wrapper.get('form select').element as HTMLSelectElement).value).toBe('ranking')
    await wrapper.get('form button[type="button"]').trigger('click')
    await wrapper.findAll('article')[0]!.findAll('button')[0]!.trigger('click')
    await wrapper.get('form select').setValue('benchmark')
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(categoryButton(wrapper, 'benchmark').attributes('aria-pressed')).toBe('true')
    expect(wrapper.findAll('article')).toHaveLength(3)
    expect(wrapper.text()).toContain('Folkbench')
    await categoryButton(wrapper, 'ranking').trigger('click')
    expect(wrapper.findAll('article')).toHaveLength(2)
    expect(wrapper.findAll('article').some(card => card.text().includes('Folkbench'))).toBe(false)
  })
  it('separates service status and pricing references with the correct family filters and link labels', async () => {
    const wrapper = render(); await flushPromises(); await selectKind(wrapper, 'channel')
    expect(wrapper.findAll('.quality-resource-groups button')).toHaveLength(4)
    expect(wrapper.findAll('.quality-resource-kinds button')).toHaveLength(6)
    await categoryButton(wrapper, 'status').trigger('click')
    expect(wrapper.findAll('article')).toHaveLength(2)
    expect(wrapper.findAll('article a')[0]!.text()).toContain('quality.external.openByKind.status')
    await wrapper.get('.quality-resource-filters select').setValue('gpt')
    expect(wrapper.findAll('article')).toHaveLength(1)
    expect(wrapper.find('a')!.attributes('href')).toBe('https://status.openai.com/')
    await wrapper.get('.quality-resource-filters select').setValue('claude')
    expect(wrapper.find('a')!.attributes('href')).toBe('https://status.claude.com/')
    await categoryButton(wrapper, 'pricing').trigger('click')
    expect(wrapper.findAll('article')).toHaveLength(2)
    expect(wrapper.text()).toContain('Claude API pricing')
    expect(wrapper.text()).toContain('Models.dev')
    expect(wrapper.findAll('article a')[0]!.text()).toContain('quality.external.openByKind.pricing')
    await wrapper.get('.quality-external-toolbar .primary').trigger('click')
    expect((wrapper.get('form select').element as HTMLSelectElement).value).toBe('pricing')
    expect(qualityAPI.saveExternalTools).not.toHaveBeenCalled()
  })
  it('rejects unsafe URLs and retains edits when saving conflicts', async () => {
    const wrapper = render(); await flushPromises(); await selectKind(wrapper, 'channel')
    await wrapper.findAll('article')[0]!.findAll('button')[0]!.trigger('click')
    await wrapper.get('form input[type="url"]').setValue('javascript:alert(1)')
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(qualityAPI.saveExternalTools).not.toHaveBeenCalled()
    expect(wrapper.get('[role="alert"]').text()).toBe('quality.external.invalid')
    await wrapper.get('form input[type="url"]').setValue('https://example.com/')
    vi.mocked(qualityAPI.saveExternalTools).mockRejectedValue(new Error('private database detail'))
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toBe('quality.external.saveError')
    expect(wrapper.find('form').exists()).toBe(true)
    expect(wrapper.text()).not.toContain('private database detail')
  })
  it('renders site descriptions as text and refuses unsafe stored links', async () => {
    vi.mocked(qualityAPI.externalTools).mockResolvedValue({ version: 1, items: [{ ...externalTools.items[0]!, description: '<script>alert(1)</script>', url: 'javascript:alert(1)' }] })
    const wrapper = render(); await flushPromises(); await selectKind(wrapper, 'channel')
    expect(wrapper.text()).toContain('<script>alert(1)</script>')
    expect(wrapper.find('script').exists()).toBe(false)
    expect(wrapper.find('a').exists()).toBe(false)
  })
})

describe('Business resource discovery', () => {
  it('searches across groups by tags, domain and original notes without modifying the list', async () => {
    const wrapper = render(); await flushPromises()
    expect(wrapper.findAll('article')).toHaveLength(12)
    await selectKind(wrapper, 'channel')
    await wrapper.get('input[type="search"]').setValue('SMTP')
    expect(wrapper.findAll('article')).toHaveLength(1)
    expect(wrapper.text()).toContain('Zoho ZeptoMail')
    expect(wrapper.get('.quality-resource-groups button').attributes('aria-pressed')).toBe('true')
    await wrapper.get('input[type="search"]').setValue('免税州')
    expect(wrapper.findAll('article')).toHaveLength(1)
    expect(wrapper.text()).toContain('AI 比价 选择免税州+菲律宾区')
    await wrapper.get('input[type="search"]').setValue('RESEND.COM')
    expect(wrapper.findAll('article')).toHaveLength(1)
    expect(wrapper.text()).toContain('quality.external.usages.trial')
    expect(qualityAPI.saveExternalTools).not.toHaveBeenCalled()
  })
  it('keeps general business resources visible with model filters and filters trial resources', async () => {
    const wrapper = render(); await flushPromises()
    await selectKind(wrapper, 'upstream')
    expect(wrapper.findAll('article')).toHaveLength(6)
    await wrapper.get('.quality-resource-filters select').setValue('gpt')
    expect(wrapper.findAll('article')).toHaveLength(6)
    await wrapper.get('.quality-resource-filters select').setValue('general')
    expect(wrapper.findAll('article')).toHaveLength(5)
    expect(wrapper.text()).not.toContain('OpenRouter')
    await wrapper.findAll('.quality-resource-groups button')[0]!.trigger('click')
    await wrapper.findAll('.quality-resource-filters select')[1]!.setValue('trial')
    expect(wrapper.findAll('article')).toHaveLength(1)
    expect(wrapper.text()).toContain('Resend')
  })
  it('pages through the saved library and resets paging when searching', async () => {
    const wrapper = render(); await flushPromises()
    expect(wrapper.findAll('article')).toHaveLength(12)
    await wrapper.get('.quality-resource-more').trigger('click')
    expect(wrapper.findAll('article')).toHaveLength(24)
    await wrapper.get('.quality-resource-more').trigger('click')
    await wrapper.get('.quality-resource-more').trigger('click')
    expect(wrapper.findAll('article')).toHaveLength(42)
    expect(wrapper.find('.quality-resource-more').exists()).toBe(false)
    await wrapper.get('input[type="search"]').setValue('not-in-this-catalog')
    expect(wrapper.findAll('article')).toHaveLength(0)
    await wrapper.get('input[type="search"]').setValue('')
    expect(wrapper.findAll('article')).toHaveLength(12)
  })
  it('preserves original notes and review evidence when editing usage and tags on a general resource', async () => {
    const wrapper = render(); await flushPromises()
    await wrapper.get('input[type="search"]').setValue('resend.com/signup')
    await wrapper.get('article button').trigger('click')
    const form = wrapper.get('form')
    expect(form.findAll('input[type="checkbox"]').every(input => !(input.element as HTMLInputElement).checked)).toBe(true)
    await form.findAll('select')[1]!.setValue('using')
    await form.get('input[maxlength="247"]').setValue('Email, SMTP, SMTP')
    await form.trigger('submit'); await flushPromises()
    const submitted = vi.mocked(qualityAPI.saveExternalTools).mock.calls[0]![0].items.find(item => item.id === 'resend')!
    expect(submitted).toMatchObject({ usage: 'using', families: [], tags: ['Email', 'SMTP'], notes: '邮箱验证，正在试用', origin: 'user', review: 'public', reviewed_at: '2026-11-04', reference_url: 'https://resend.com/' })
    expect(wrapper.findAll('article')).toHaveLength(3)
    expect(wrapper.text()).toContain('Resend')
    expect(wrapper.get('input[type="search"]').element).toHaveProperty('value', '')
  })
  it('blocks unsafe reference URLs and duplicate links while retaining the draft', async () => {
    const wrapper = render(); await flushPromises()
    await wrapper.get('input[type="search"]').setValue('resend.com/signup')
    await wrapper.get('article button').trigger('click')
    await wrapper.get('form input[type="url"][maxlength="2048"]').setValue('https://resend.com/signup')
    await wrapper.get('form details input[type="url"]').setValue('javascript:alert(1)')
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(qualityAPI.saveExternalTools).not.toHaveBeenCalled()
    await wrapper.get('form details input[type="url"]').setValue('https://resend.com/')
    await wrapper.get('form button[type="button"]').trigger('click')
    await wrapper.get('.quality-external-toolbar .primary').trigger('click')
    await wrapper.get('form input:not([type])').setValue('Duplicate')
    await wrapper.get('form select').setValue('email')
    await wrapper.get('form input[type="url"]').setValue('https://resend.com/signup/')
    await wrapper.get('form textarea').setValue('Duplicate email provider')
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toBe('quality.external.duplicate')
    expect(qualityAPI.saveExternalTools).not.toHaveBeenCalled()
  })
})
